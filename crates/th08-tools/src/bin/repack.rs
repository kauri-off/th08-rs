//! th08.pak from th08.dat (docs/arch/ASSETS_FORMAT.md §3.1, §3.5): `repack <game dir> <out dir> [--frame-mb N]
//! [--level L] [--table FILE]`. Every entry keeps the bytes `Archive::read` returns (01 §5–§6), zstd-compressed; the
//! written pack is read back and checked entry by entry. `--table` writes core's vanilla Logic sha256 table.

use anyhow::{Context, bail, ensure};
use std::fmt::Write as _;
use std::path::PathBuf;
use std::time::Instant;
use th08_formats::archive::Archive;
use th08_formats::pack::{self, Kind, Layer, Pack};

struct Args {
    game: PathBuf,
    out: PathBuf,
    frame_mb: usize,
    level: i32,
    table: Option<PathBuf>,
}

fn args() -> anyhow::Result<Args> {
    let mut pos = Vec::new();
    let (mut frame_mb, mut level, mut table) = (4, 19, None);
    let mut it = std::env::args().skip(1);
    while let Some(a) = it.next() {
        match a.as_str() {
            "--frame-mb" => frame_mb = it.next().context("--frame-mb N")?.parse()?,
            "--level" => level = it.next().context("--level L")?.parse()?,
            "--table" => table = Some(PathBuf::from(it.next().context("--table FILE")?)),
            _ if a.starts_with("--") => bail!("unknown option {a}"),
            _ => pos.push(PathBuf::from(a)),
        }
    }
    let [game, out]: [PathBuf; 2] = pos.try_into().map_err(|_| {
        anyhow::anyhow!(
            "usage: repack <game dir> <out dir> [--frame-mb N] [--level L] [--table FILE]"
        )
    })?;
    Ok(Args {
        game,
        out,
        frame_mb,
        level,
        table,
    })
}

// zstd frame of `raw`; window covers a whole frame so solid frames match across files.
fn compress(raw: &[u8], level: i32) -> anyhow::Result<Vec<u8>> {
    let mut c = zstd::bulk::Compressor::new(level)?;
    let wlog = (usize::BITS - raw.len().max(1 << 10).leading_zeros()).clamp(10, 27);
    c.set_parameter(zstd::zstd_safe::CParameter::WindowLog(wlog))?;
    c.include_checksum(true)?;
    Ok(c.compress(raw)?)
}

// `crates/th08-core/src/vanilla.rs`: Logic entries of the original th08.dat, sha256 of `Archive::read` bytes.
fn table_source(ar: &Archive) -> anyhow::Result<String> {
    let mut s = String::from(
        "//! Vanilla Logic-entry sha256 table (docs/arch/ASSETS_FORMAT.md §3.1, §3.3): sha256 of `Archive::read(name)` for\n\
         //! every Logic-layer entry of the original th08.dat (01 §5); hashes only. Generated by `repack --table`.\n\n\
         pub(crate) const LOGIC_SHA256: &[(&str, &str)] = &[\n",
    );
    for n in ar
        .names()
        .iter()
        .filter(|n| pack::layer_of(n) == Layer::Logic)
    {
        let h = pack::sha256(&ar.read(n)?);
        let hex: String = h.iter().map(|b| format!("{b:02x}")).collect();
        writeln!(s, "    (\"{n}\", \"{hex}\"),")?;
    }
    s.push_str("];\n");
    Ok(s)
}

fn main() -> anyhow::Result<()> {
    let a = args()?;
    let dat = th08::sources::find_file(&a.game, "th08.dat");
    let raw = std::fs::read(&dat).with_context(|| dat.display().to_string())?;
    let dat_len = raw.len();
    let ar = Archive::from_bytes(raw)?;
    let t = Instant::now();
    let data: Vec<(String, Vec<u8>)> = ar
        .names()
        .iter()
        .map(|n| Ok((n.clone(), ar.read(n)?)))
        .collect::<anyhow::Result<_>>()?;
    let t_dat = t.elapsed();
    let files: Vec<(&str, &[u8])> = data
        .iter()
        .map(|(n, b)| (n.as_str(), b.as_slice()))
        .collect();
    let t = Instant::now();
    let mut err = None;
    let bytes = pack::write(
        Kind::Content,
        &files,
        a.frame_mb << 20,
        &mut |b: &[u8]| {
            compress(b, a.level).unwrap_or_else(|e| {
                err.get_or_insert(e);
                b.to_vec()
            })
        },
    );
    if let Some(e) = err {
        return Err(e);
    }
    let t_enc = t.elapsed();
    std::fs::create_dir_all(&a.out)?;
    let out = a.out.join("th08.pak");
    std::fs::write(&out, &bytes)?;

    // Self-verify from the written file: same names in order, every entry = Archive::read, hashes match.
    let t = Instant::now();
    let p = Pack::from_bytes(std::fs::read(&out)?)?;
    ensure!(p.names() == ar.names(), "entry names / order differ");
    for (e, (n, b)) in p.entries().iter().zip(&data) {
        ensure!(e.sha256 == pack::sha256(b), "{n}: manifest hash");
        ensure!(&p.read(n)? == b, "{n}: decoded bytes differ");
    }
    let t_pack = t.elapsed();
    let unpacked: usize = data.iter().map(|d| d.1.len()).sum();
    let max_frame = p.frames().iter().map(|f| f.size).max().unwrap_or(0);
    println!(
        "{}: {} entries, {} frames (largest {max_frame} B decoded), {} B (th08.dat {dat_len} B, unpacked {unpacked} B)",
        out.display(),
        p.entries().len(),
        p.frames().len(),
        bytes.len()
    );
    println!(
        "verify ok; read all entries: th08.dat {:.3} s, th08.pak {:.3} s (incl. sha256); encode {:.1} s",
        t_dat.as_secs_f64(),
        t_pack.as_secs_f64(),
        t_enc.as_secs_f64()
    );
    if let Some(path) = a.table {
        std::fs::write(&path, table_source(&ar)?)?;
        println!("vanilla table → {}", path.display());
    }
    Ok(())
}
